"""Centroid-only index of every admin-1 region, for placing a site that has no coordinates.

The per-country files in app/ui/app/data/geo/admin1 already carry a centroid per region, but each
one also carries its outlines — the United States is 30 KB of which the shapes are 29. Placing a
site needs the centre and nothing else, and it needs every country at once, because the name of a
site says which region it is in long before it says which country.

So this writes one file holding the centre of all of them: code, name, latitude, longitude, by
country. It is read through a dynamic import, which means an estate that tags its coordinates
never fetches it.

Two decimal places is about a kilometre, and what is being placed is a whole state.

    python3 scripts/admin1_centroids.py
"""
import json, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE.parent / "app/ui/app/data/geo/admin1"
OUT = SRC / "centroids.ts"

def main() -> int:
    dec = json.JSONDecoder()
    table: dict[str, list] = {}
    for f in sorted(SRC.glob("*.ts")):
        if f.name in ("load.ts", "centroids.ts"):
            continue
        src = f.read_text(encoding="utf-8")
        i = src.find("export default")
        if i < 0:
            continue
        data, _ = dec.raw_decode(src[i + len("export default"):].lstrip())
        rows = [[r["code"], r["name"], round(r["lat"], 2), round(r["lon"], 2)]
                for r in data["regions"] if r.get("code") and r.get("name")]
        if rows:
            table[data["cc"]] = sorted(rows)
    if not table:
        print("no admin-1 files found", file=sys.stderr)
        return 1

    body = json.dumps(table, separators=(",", ":"), ensure_ascii=False)
    OUT.write_text(
        "// Generated by scripts/admin1_centroids.py from the per-country files beside it. Do not edit.\n"
        "//\n"
        "// The centre of every admin-1 region on earth — state, province, prefecture — by country:\n"
        "// [code, name, lat, lon]. Loaded only when an estate has sites that nothing else places.\n"
        "export type Centroid = [code: string, name: string, lat: number, lon: number];\n"
        f"export default {body} as Record<string, Centroid[]>;\n",
        encoding="utf-8")
    regions = sum(len(v) for v in table.values())
    print(f"wrote {OUT.relative_to(HERE.parent)}: {regions} regions in {len(table)} countries,"
          f" {OUT.stat().st_size // 1024} KB")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
